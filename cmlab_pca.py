from pathlib import Path


IMAGES_DIR = "/sample_data/images_grayscale"
IMAGE_EXT = "*.jpg.chip.jpg"
CONVERT_TO_GRAYSCALE = True
N_PC_TO_SHOW = 5
VARIANCE_THRESHOLD = 0.90

