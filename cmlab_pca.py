# ----------------------------------------------------------------------
# 1. CARICAMENTO DELLE IMMAGINI
# ----------------------------------------------------------------------
def load_images(images_path: Path, ext: str, grayscale: bool):
    filepaths = sorted(images_path.glob(ext))
    if not filepaths:
        raise FileNotFoundError(
            f"Nessuna immagine trovata in {images_path} con estensione {ext}. "
            "Controlla IMAGES_DIR e IMAGE_EXT."
        )

    images = []
    for fp in filepaths:
        img = img_as_float(io.imread(fp))  # valori in [0, 1]
        if grayscale and img.ndim == 3:
            img = color.rgb2gray(img)
        images.append(img)

    shapes = {img.shape for img in images}
    if len(shapes) > 1:
        raise ValueError(
            f"Le immagini hanno shape diverse: {shapes}. "
            "Devono avere tutte le stesse dimensioni prima della PCA "
            "(ridimensionale con skimage.transform.resize se necessario)."
        )

    img_shape = images[0].shape
    X = np.array([img.flatten() for img in images])  # shape (n, p)
    return X, img_shape, filepaths


print("Caricamento immagini...")
X, img_shape, filepaths = load_images(IMAGES_PATH, IMAGE_EXT, CONVERT_TO_GRAYSCALE)
n, p = X.shape
print(f"Caricate {n} immagini, ciascuna con shape {img_shape} -> vettori di dimensione {p}")

# ----------------------------------------------------------------------
# 2. PCA
# ----------------------------------------------------------------------
mean_image = X.mean(axis=0)
X_centered = X - mean_image

pca = PCA()
scores = pca.fit_transform(X_centered)          # (n, n_components) -> predittori per il modello di encoding
components = pca.components_                    # (n_components, p)
explained_var_ratio = pca.explained_variance_ratio_
cum_var = np.cumsum(explained_var_ratio)

n_components_selected = int(np.searchsorted(cum_var, VARIANCE_THRESHOLD) + 1)
print(f"Numero di PC necessarie per spiegare almeno il {VARIANCE_THRESHOLD:.0%} "
      f"della varianza: {n_components_selected} (su un massimo di {len(explained_var_ratio)})")

# ----------------------------------------------------------------------
# 3. VISUALIZZAZIONE DELLE PRIME COMPONENTI (min score / media / max score)
# ----------------------------------------------------------------------
def show_pc_effect(pc_idx, scores, components, mean_image, img_shape, grayscale):
    s_min = scores[:, pc_idx].min()
    s_max = scores[:, pc_idx].max()
    v = components[pc_idx]

    img_min = (mean_image + s_min * v).reshape(img_shape)
    img_avg = mean_image.reshape(img_shape)
    img_max = (mean_image + s_max * v).reshape(img_shape)

    fig, axes = plt.subplots(1, 3, figsize=(9, 3))
    cmap = "gray" if grayscale else None
    for ax, im, title in zip(axes, [img_min, img_avg, img_max],
                              ["min score", "media", "max score"]):
        ax.imshow(np.clip(im, 0, 1), cmap=cmap)
        ax.set_title(title)
        ax.axis("off")
    fig.suptitle(f"PC {pc_idx + 1} "
                 f"(varianza spiegata: {explained_var_ratio[pc_idx]:.2%})")
    fig.tight_layout()
    return fig

print("Generazione figure per le prime componenti...")
for i in range(N_PC_TO_SHOW):
    fig = show_pc_effect(i, scores, components, mean_image, img_shape, CONVERT_TO_GRAYSCALE)
    fig.savefig(BASE_DIR / f"pc_{i + 1}_effect.png", dpi=150)
plt.show()

# ----------------------------------------------------------------------
